/// 0 = not set yet (follow the system), 1 = Korean, 2 = English.
static LANGUAGE: AtomicU8 = AtomicU8::new(0);

/// "ko" when the system language is Korean, otherwise "en".
pub fn system_language() -> &'static str {
    if sys_locale::get_locale().is_some_and(|l| l.to_lowercase().starts_with("ko")) { "ko" } else { "en" }
}

/// Applies the `language` setting ("ko" or "en").
pub fn set_language(code: &str) {
    let v = match code {
        "ko" => 1,
        "en" => 2,
        _ => 0,
    };
    LANGUAGE.store(v, Ordering::Relaxed);
}

pub fn texts() -> &'static Texts {
    match LANGUAGE.load(Ordering::Relaxed) {
        1 => &KO,
        2 => &EN,
        _ if system_language() == "ko" => &KO,
        _ => &EN,
    }
}
